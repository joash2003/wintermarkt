using UnityEngine;
using UnityEngine.EventSystems;
using Wintermarkt.Core;

namespace Wintermarkt
{
    public enum FestivalState { Menu, Playing, Paused, Results }

    public sealed class MarketGame : MonoBehaviour
    {
        public MarketSimulation Simulation { get; private set; }
        public MarketWorld World { get; private set; }
        public FestivalState State { get; private set; }
        public string BuildChoice { get; private set; }
        public MarketBuilding Selected { get; private set; }
        public string Message { get; private set; }
        public bool Muted { get; private set; }
        public MarketUI UI { get; private set; }
        Camera view;
        Vector3 focus, lastMouse;
        Cell lastCell = new Cell(-999, -999);
        string lastChoice;
        bool lastValid, previewVisible;
        int lastWave;
        AudioSource audioSource;
        AudioClip click;
        MarketSettings settings;
        SiteData site;

        void Start()
        {
            var config = Resources.Load<TextAsset>("Wintermarkt/market"); var map = Resources.Load<TextAsset>("Wintermarkt/site");
            if (!config || !map) throw new System.InvalidOperationException("Missing Wintermarkt market.json or site.json.");
            settings = JsonUtility.FromJson<MarketSettings>(config.text); site = JsonUtility.FromJson<SiteData>(map.text);
            view = Camera.main;
            if (!view) throw new System.InvalidOperationException("Open Market.unity generated by Tools > Wintermarkt > Create or Repair Project.");
            view.orthographic = true; view.orthographicSize = 45;
            view.transform.rotation = Quaternion.Euler(55, 30, 0);
            World = gameObject.AddComponent<MarketWorld>();
            audioSource = gameObject.AddComponent<AudioSource>();
            click = AudioClip.Create("Original soft bell", 8000, 1, 44100, false);
            var samples = new float[8000]; for (int i = 0; i < samples.Length; i++) samples[i] = Mathf.Sin(i * 2 * Mathf.PI * 620 / 44100) * Mathf.Exp(-i / 1400f) * .15f; click.SetData(samples, 0);
            Muted = PlayerPrefs.GetInt("WintermarktMuted", 0) == 1;
            UI = gameObject.AddComponent<MarketUI>(); UI.Initialize(this);
            ResetSimulation(); State = FestivalState.Menu; Simulation.Paused = true; UI.Refresh();
            if (System.Array.IndexOf(System.Environment.GetCommandLineArgs(), "-demo") >= 0) Demo();
        }

        // `-demo` on the command line opens the market with two stalls by the entrance: screenshots and smoke tests.
        void Demo()
        {
            StartFestival(); Application.runInBackground = true;
            Cell e = Simulation.Site.Entrance; var cells = new System.Collections.Generic.List<Cell>();
            for (int y = 0; y < Simulation.Site.Height; y++) for (int x = 0; x < Simulation.Site.Width; x++) if (Mathf.Abs(x - e.x) + Mathf.Abs(y - e.y) > 4) cells.Add(new Cell(x, y));
            cells.Sort((a, b) => (Mathf.Abs(a.x - e.x) + Mathf.Abs(a.y - e.y)).CompareTo(Mathf.Abs(b.x - e.x) + Mathf.Abs(b.y - e.y)));
            foreach (var id in new[] { "punsch", "pastry" }) foreach (var c in cells) if (Simulation.TryPlace(id, c, out _)) break;
            focus = World.World(Simulation.Buildings[0].Origin); view.orthographicSize = 32; PlaceCamera();
        }

        void ResetSimulation()
        {
            Simulation = new MarketSimulation(settings, site); World.Initialize(Simulation);
            BuildChoice = null; Selected = null; focus = World.World(Simulation.Site.Entrance) * .3f; previewVisible = false; lastChoice = null; lastCell = new Cell(-999, -999);
            Message = "Choose a stall, then place it on an open plot. Leave room for its queue."; lastWave = 0;
            PlaceCamera();
        }
        public void StartFestival() { ResetSimulation(); State = FestivalState.Playing; UI.Refresh(); }
        public void Menu() { State = FestivalState.Menu; Simulation.Paused = true; CancelBuild(); UI.Refresh(); }
        public void TogglePause()
        {
            if (State == FestivalState.Playing) { State = FestivalState.Paused; Simulation.Paused = true; }
            else if (State == FestivalState.Paused) { State = FestivalState.Playing; Simulation.Paused = false; }
            HidePreview(); UI.Refresh();
        }
        public void ChooseBuild(string id)
        {
            if (State != FestivalState.Playing) return;
            BuildChoice = id; Selected = null; lastChoice = null; Message = "Green: build here. Red: blocked or unaffordable. Right-click cancels."; UI.RefreshSelection();
        }
        public void CancelBuild() { BuildChoice = null; HidePreview(); }
        public void Upgrade()
        {
            string reason;
            if (Selected == null) return;
            bool ok = Simulation.TryUpgrade(Selected.Id, out reason); Message = reason;
            if (ok) { PlayClick(); World.Synchronize(0); } UI.RefreshSelection();
        }
        public void Remove()
        {
            string reason;
            if (Selected == null) return;
            if (Simulation.TryRemove(Selected.Id, out reason)) { Selected = null; PlayClick(); World.Synchronize(0); }
            Message = reason; UI.RefreshSelection();
        }
        public void ToggleSound() { Muted = !Muted; PlayerPrefs.SetInt("WintermarktMuted", Muted ? 1 : 0); UI.Refresh(); }
        public void PlayClick() { if (!Muted && click) audioSource.PlayOneShot(click); }
        public void Quit() { Application.Quit(); }
        void HidePreview() { if (previewVisible) World.Preview(null, default(Cell), false); previewVisible = false; }

        void Update()
        {
            if (Simulation == null) return;
            if (Input.GetKeyDown(KeyCode.M)) ToggleSound();
            if (Input.GetKeyDown(KeyCode.Escape)) { if (BuildChoice != null) CancelBuild(); else TogglePause(); }
            HandleCamera();
            float dt = State == FestivalState.Playing ? Time.deltaTime : 0;
            Simulation.Tick(dt); World.Synchronize(dt);
            if (Simulation.Wave != lastWave)
            { lastWave = Simulation.Wave; Message = "Wave " + (lastWave + 1) + ": " + Simulation.CurrentWave.title + ". Send " + Simulation.CurrentWave.target + " visitors home happy."; PlayClick(); }
            if (State == FestivalState.Playing && Simulation.Finished) { State = FestivalState.Results; HidePreview(); UI.Refresh(); return; }
            if (State != FestivalState.Playing) return;
            if (Input.GetMouseButtonDown(1)) CancelBuild();
            if (EventSystem.current && EventSystem.current.IsPointerOverGameObject()) { HidePreview(); return; }
            var plane = new Plane(Vector3.up, Vector3.zero); var ray = view.ScreenPointToRay(Input.mousePosition); float distance;
            if (!plane.Raycast(ray, out distance)) { HidePreview(); return; }
            Cell cell = World.Grid(ray.GetPoint(distance));
            if (BuildChoice != null)
            {
                string reason; bool valid = Simulation.CanPlace(BuildChoice, cell, out reason); Message = reason;
                if (!previewVisible || cell != lastCell || BuildChoice != lastChoice || valid != lastValid)
                {
                    World.Preview(Simulation.FindDefinition(BuildChoice), cell, valid); previewVisible = true;
                    lastCell = cell; lastChoice = BuildChoice; lastValid = valid;
                }
                if (Input.GetMouseButtonDown(0))
                {
                    if (Simulation.TryPlace(BuildChoice, cell, out reason))
                    { Selected = Simulation.Buildings[Simulation.Buildings.Count - 1]; CancelBuild(); PlayClick(); World.Synchronize(0); UI.RefreshSelection(); }
                    Message = reason;
                }
            }
            else if (Input.GetMouseButtonDown(0)) { Selected = Simulation.At(cell); UI.RefreshSelection(); }
        }
        void HandleCamera()
        {
            float dx = (Input.GetKey(KeyCode.D) || Input.GetKey(KeyCode.RightArrow) ? 1 : 0) - (Input.GetKey(KeyCode.A) || Input.GetKey(KeyCode.LeftArrow) ? 1 : 0);
            float dz = (Input.GetKey(KeyCode.W) || Input.GetKey(KeyCode.UpArrow) ? 1 : 0) - (Input.GetKey(KeyCode.S) || Input.GetKey(KeyCode.DownArrow) ? 1 : 0);
            Vector3 forward = Vector3.ProjectOnPlane(view.transform.forward, Vector3.up).normalized;
            focus += (view.transform.right * dx + forward * dz).normalized * Time.unscaledDeltaTime * view.orthographicSize * .6f;
            if (Input.GetMouseButtonDown(2)) lastMouse = Input.mousePosition;
            if (Input.GetMouseButton(2))
            {
                Vector3 delta = Input.mousePosition - lastMouse; lastMouse = Input.mousePosition;
                focus -= (view.transform.right * delta.x + forward * delta.y) * view.orthographicSize / Screen.height * 2;
            }
            if (!EventSystem.current || !EventSystem.current.IsPointerOverGameObject()) view.orthographicSize = Mathf.Clamp(view.orthographicSize - Input.mouseScrollDelta.y * 5, 28, 160);
            // The grid is only the market corner; the margin lets the camera travel over the rest of the park.
            float halfWidth = Simulation.Site.Width * World.CellSize * .5f + 150, halfHeight = Simulation.Site.Height * World.CellSize * .5f + 150;
            focus.x = Mathf.Clamp(focus.x, -halfWidth, halfWidth); focus.z = Mathf.Clamp(focus.z, -halfHeight, halfHeight); PlaceCamera();
        }
        void PlaceCamera() { view.transform.position = focus - view.transform.forward * 220; }
        void OnDestroy() { if (click) Destroy(click); }
    }
}
